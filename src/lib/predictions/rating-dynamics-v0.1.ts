export const RATING_DYNAMICS_MODEL_VERSION_V01 =
  "dictaziq-rating-dynamics-v0.1" as const;

export const RATING_DYNAMICS_FULL_MIN_OBSERVATIONS_V01 =
  4 as const;

export const RATING_DYNAMICS_FULL_MIN_SPAN_DAYS_V01 =
  21 as const;

export type RatingDynamicsStatusV01 =
  | "available"
  | "partial"
  | "unavailable";

export type RatingTrendDirectionV01 =
  | "rising"
  | "falling"
  | "flat"
  | "unavailable";

export type RatingCurrentPositionV01 =
  | "period_high"
  | "period_low"
  | "inside_range"
  | "flat_range"
  | "unavailable";

export type RatingDynamicsSnapshotV01 = {
  rating: number;

  snapshotDate: string;

  source: string;
};

export type RatingDynamicsInputV01 = {
  teamId: string;

  teamName: string;

  asOfDate: string;

  snapshots:
    RatingDynamicsSnapshotV01[];
};

export type RatingDynamicsResultV01 = {
  modelVersion:
    typeof RATING_DYNAMICS_MODEL_VERSION_V01;

  validationStatus:
    "experimental";

  teamId: string;

  teamName: string;

  asOfDate: string;

  status:
    RatingDynamicsStatusV01;

  source:
    string | null;

  /*
   * IMPORTANT:
   *
   * This is the actual latest FootballDatabase
   * rating.
   *
   * No trend-adjusted replacement rating is
   * generated by this model.
   */
  currentRating:
    number | null;

  currentSnapshotDate:
    string | null;

  previousRating:
    number | null;

  previousSnapshotDate:
    string | null;

  lastChange:
    number | null;

  observationCount:
    number;

  historySpanDays:
    number | null;

  /*
   * Total movement from the oldest observation
   * in the available period to the current rating.
   */
  netChange:
    number | null;

  /*
   * Linear rating trajectory normalised to
   * rating points per seven days.
   *
   * These are descriptive statistics,
   * not additional team-strength ratings.
   */
  shortTermSlopePer7Days:
    number | null;

  mediumTermSlopePer7Days:
    number | null;

  shortTermObservations:
    number;

  mediumTermObservations:
    number;

  direction:
    RatingTrendDirectionV01;

  /*
   * Descriptive volatility of consecutive
   * rating changes.
   */
  meanAbsoluteStepChange:
    number | null;

  stepChangeStandardDeviation:
    number | null;

  positiveSteps:
    number;

  negativeSteps:
    number;

  flatSteps:
    number;

  periodMinimumRating:
    number | null;

  periodMaximumRating:
    number | null;

  periodRatingRange:
    number | null;

  currentPosition:
    RatingCurrentPositionV01;

  recommendationStatus:
    "not_evaluated";

  calibratedProbability:
    null;

  reason:
    string;
};

function assertDate(
  value: string,
  label: string,
): void {
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(
      value,
    )
  ) {
    throw new Error(
      `${label} must use YYYY-MM-DD format.`,
    );
  }

  const parsed =
    new Date(
      `${value}T00:00:00.000Z`,
    );

  if (
    !Number.isFinite(
      parsed.getTime(),
    ) ||
    parsed
      .toISOString()
      .slice(
        0,
        10,
      ) !== value
  ) {
    throw new Error(
      `${label} is invalid.`,
    );
  }
}

function dateMs(
  value: string,
): number {
  return new Date(
    `${value}T00:00:00.000Z`,
  ).getTime();
}

function daysBetween(
  first: string,
  second: string,
): number {
  return (
    dateMs(second) -
    dateMs(first)
  ) / 86_400_000;
}

function roundMetric(
  value: number,
): number {
  return Number(
    value.toFixed(4),
  );
}

function standardDeviation(
  values: number[],
): number | null {
  if (
    values.length === 0
  ) {
    return null;
  }

  const mean =
    values.reduce(
      (
        total,
        value,
      ) =>
        total + value,
      0,
    ) /
    values.length;

  const variance =
    values.reduce(
      (
        total,
        value,
      ) => {
        const difference =
          value - mean;

        return (
          total +
          difference *
            difference
        );
      },
      0,
    ) /
    values.length;

  return roundMetric(
    Math.sqrt(
      variance,
    ),
  );
}

/*
 * Ordinary least-squares slope of rating
 * against elapsed calendar days.
 *
 * Returned value:
 *
 * rating points / 7 days
 *
 * This normalises differences in snapshot
 * spacing without changing the actual current
 * rating itself.
 */
function calculateSlopePer7Days(
  snapshots:
    RatingDynamicsSnapshotV01[],
): number | null {
  if (
    snapshots.length <
    2
  ) {
    return null;
  }

  const origin =
    dateMs(
      snapshots[0]
        .snapshotDate,
    );

  const points =
    snapshots.map(
      (snapshot) => ({
        x:
          (
            dateMs(
              snapshot
                .snapshotDate,
            ) -
            origin
          ) /
          86_400_000,

        y:
          snapshot.rating,
      }),
    );

  const meanX =
    points.reduce(
      (
        total,
        point,
      ) =>
        total +
        point.x,
      0,
    ) /
    points.length;

  const meanY =
    points.reduce(
      (
        total,
        point,
      ) =>
        total +
        point.y,
      0,
    ) /
    points.length;

  let numerator =
    0;

  let denominator =
    0;

  for (
    const point
    of points
  ) {
    const dx =
      point.x -
      meanX;

    numerator +=
      dx *
      (
        point.y -
        meanY
      );

    denominator +=
      dx * dx;
  }

  if (
    denominator === 0
  ) {
    return null;
  }

  const slopePerDay =
    numerator /
    denominator;

  return roundMetric(
    slopePerDay * 7,
  );
}

function directionFromSlope(
  slope:
    number | null,
): RatingTrendDirectionV01 {
  if (
    slope === null
  ) {
    return "unavailable";
  }

  /*
   * Floating-point tolerance only.
   *
   * This is NOT a football-model threshold.
   */
  if (
    Math.abs(
      slope,
    ) <
    1e-10
  ) {
    return "flat";
  }

  return slope > 0
    ? "rising"
    : "falling";
}

function validateInput(
  input:
    RatingDynamicsInputV01,
): RatingDynamicsSnapshotV01[] {
  if (
    !input.teamId.trim()
  ) {
    throw new Error(
      "Team ID must not be empty.",
    );
  }

  if (
    !input.teamName.trim()
  ) {
    throw new Error(
      "Team name must not be empty.",
    );
  }

  assertDate(
    input.asOfDate,
    "As-of date",
  );

  const seenDates =
    new Set<string>();

  let commonSource:
    string | null =
      null;

  for (
    const snapshot
    of input.snapshots
  ) {
    if (
      !Number.isFinite(
        snapshot.rating,
      ) ||
      !Number.isInteger(
        snapshot.rating,
      ) ||
      snapshot.rating < 0
    ) {
      throw new Error(
        "Rating must be a non-negative finite integer.",
      );
    }

    assertDate(
      snapshot.snapshotDate,
      "Rating snapshot date",
    );

    if (
      dateMs(
        snapshot.snapshotDate,
      ) >
      dateMs(
        input.asOfDate,
      )
    ) {
      throw new Error(
        "Rating dynamics cannot use a snapshot after the as-of date.",
      );
    }

    if (
      seenDates.has(
        snapshot.snapshotDate,
      )
    ) {
      throw new Error(
        `Duplicate rating snapshot date: ${snapshot.snapshotDate}.`,
      );
    }

    seenDates.add(
      snapshot.snapshotDate,
    );

    const source =
      snapshot.source.trim();

    if (
      !source
    ) {
      throw new Error(
        "Rating source must not be empty.",
      );
    }

    if (
      commonSource === null
    ) {
      commonSource =
        source;
    } else if (
      commonSource !==
      source
    ) {
      throw new Error(
        "All rating-dynamics snapshots must come from the same source.",
      );
    }
  }

  return [
    ...input.snapshots,
  ].sort(
    (
      left,
      right,
    ) =>
      dateMs(
        left.snapshotDate,
      ) -
      dateMs(
        right.snapshotDate,
      ),
  );
}

/*
 * Rating Dynamics v0.1
 *
 * PHILOSOPHY
 * ----------
 *
 * FootballDatabase current rating remains the
 * primary quantitative representation of the
 * team's present football strength.
 *
 * This model DOES NOT:
 *
 * - create another strength rating
 * - replace the current rating
 * - add arbitrary strength points
 * - produce probabilities
 * - make a betting recommendation
 *
 * Historical ratings answer different questions:
 *
 * - Is the rating rising or falling?
 * - How quickly is it moving?
 * - Is the rating stable or volatile?
 * - Is the current number near a recent peak?
 *
 * The current rating remains mathematically intact.
 */
export function evaluateRatingDynamicsV01(
  input:
    RatingDynamicsInputV01,
): RatingDynamicsResultV01 {
  const ordered =
    validateInput(
      input,
    );

  if (
    ordered.length ===
    0
  ) {
    return {
      modelVersion:
        RATING_DYNAMICS_MODEL_VERSION_V01,

      validationStatus:
        "experimental",

      teamId:
        input.teamId,

      teamName:
        input.teamName,

      asOfDate:
        input.asOfDate,

      status:
        "unavailable",

      source:
        null,

      currentRating:
        null,

      currentSnapshotDate:
        null,

      previousRating:
        null,

      previousSnapshotDate:
        null,

      lastChange:
        null,

      observationCount:
        0,

      historySpanDays:
        null,

      netChange:
        null,

      shortTermSlopePer7Days:
        null,

      mediumTermSlopePer7Days:
        null,

      shortTermObservations:
        0,

      mediumTermObservations:
        0,

      direction:
        "unavailable",

      meanAbsoluteStepChange:
        null,

      stepChangeStandardDeviation:
        null,

      positiveSteps:
        0,

      negativeSteps:
        0,

      flatSteps:
        0,

      periodMinimumRating:
        null,

      periodMaximumRating:
        null,

      periodRatingRange:
        null,

      currentPosition:
        "unavailable",

      recommendationStatus:
        "not_evaluated",

      calibratedProbability:
        null,

      reason:
        "No historical rating observations are available. Rating dynamics are unavailable, but this must not suppress the primary current-rating forecast when that forecast is available elsewhere.",
    };
  }

  const current =
    ordered[
      ordered.length - 1
    ];

  const previous =
    ordered.length >= 2
      ? ordered[
          ordered.length - 2
        ]
      : null;

  const oldest =
    ordered[0];

  const historySpanDays =
    daysBetween(
      oldest.snapshotDate,
      current.snapshotDate,
    );

  const values =
    ordered.map(
      (snapshot) =>
        snapshot.rating,
    );

  const minimum =
    Math.min(
      ...values,
    );

  const maximum =
    Math.max(
      ...values,
    );

  const ratingRange =
    maximum -
    minimum;

  const changes:
    number[] = [];

  let positiveSteps =
    0;

  let negativeSteps =
    0;

  let flatSteps =
    0;

  for (
    let index = 1;
    index <
      ordered.length;
    index += 1
  ) {
    const change =
      ordered[index]
        .rating -
      ordered[
        index - 1
      ].rating;

    changes.push(
      change,
    );

    if (
      change > 0
    ) {
      positiveSteps +=
        1;
    } else if (
      change < 0
    ) {
      negativeSteps +=
        1;
    } else {
      flatSteps +=
        1;
    }
  }

  const meanAbsoluteStepChange =
    changes.length ===
    0
      ? null
      : roundMetric(
          changes.reduce(
            (
              total,
              change,
            ) =>
              total +
              Math.abs(
                change,
              ),
            0,
          ) /
            changes.length,
        );

  const shortWindow =
    ordered.slice(
      -4,
    );

  const mediumWindow =
    ordered.slice(
      -8,
    );

  const shortTermSlopePer7Days =
    calculateSlopePer7Days(
      shortWindow,
    );

  const mediumTermSlopePer7Days =
    calculateSlopePer7Days(
      mediumWindow,
    );

  /*
   * The most recent 4-observation trajectory is
   * the primary descriptive direction.
   *
   * If fewer than four observations exist,
   * use what is available but mark the overall
   * dynamics status PARTIAL.
   */
  const direction =
    directionFromSlope(
      shortTermSlopePer7Days,
    );

  let status:
    RatingDynamicsStatusV01;

  if (
    ordered.length <
    2
  ) {
    status =
      "unavailable";
  } else if (
    ordered.length >=
      RATING_DYNAMICS_FULL_MIN_OBSERVATIONS_V01 &&
    historySpanDays >=
      RATING_DYNAMICS_FULL_MIN_SPAN_DAYS_V01
  ) {
    status =
      "available";
  } else {
    status =
      "partial";
  }

  let currentPosition:
    RatingCurrentPositionV01;

  if (
    ratingRange === 0
  ) {
    currentPosition =
      "flat_range";
  } else if (
    current.rating ===
    maximum
  ) {
    currentPosition =
      "period_high";
  } else if (
    current.rating ===
    minimum
  ) {
    currentPosition =
      "period_low";
  } else {
    currentPosition =
      "inside_range";
  }

  const lastChange =
    previous === null
      ? null
      : current.rating -
        previous.rating;

  const netChange =
    ordered.length <
    2
      ? null
      : current.rating -
        oldest.rating;

  let reason:
    string;

  if (
    status ===
    "available"
  ) {
    reason =
      `Rating dynamics use ${ordered.length} observations spanning ${historySpanDays} days. Current rating remains ${current.rating}; trajectory statistics describe how that rating was reached and do not replace it.`;
  } else if (
    status ===
    "partial"
  ) {
    reason =
      `Only partial rating-history depth is available (${ordered.length} observations spanning ${historySpanDays} days). Numerical trajectory statistics are reported cautiously; the current rating remains the primary strength variable.`;
  } else {
    reason =
      `Only one rating observation is available. Current rating ${current.rating} remains valid as a strength measure, but no rating trajectory can yet be calculated.`;
  }

  return {
    modelVersion:
      RATING_DYNAMICS_MODEL_VERSION_V01,

    validationStatus:
      "experimental",

    teamId:
      input.teamId,

    teamName:
      input.teamName,

    asOfDate:
      input.asOfDate,

    status,

    source:
      current.source.trim(),

    currentRating:
      current.rating,

    currentSnapshotDate:
      current.snapshotDate,

    previousRating:
      previous?.rating ??
      null,

    previousSnapshotDate:
      previous
        ?.snapshotDate ??
      null,

    lastChange,

    observationCount:
      ordered.length,

    historySpanDays,

    netChange,

    shortTermSlopePer7Days,

    mediumTermSlopePer7Days,

    shortTermObservations:
      shortWindow.length,

    mediumTermObservations:
      mediumWindow.length,

    direction,

    meanAbsoluteStepChange,

    stepChangeStandardDeviation:
      standardDeviation(
        changes,
      ),

    positiveSteps,
    negativeSteps,
    flatSteps,

    periodMinimumRating:
      minimum,

    periodMaximumRating:
      maximum,

    periodRatingRange:
      ratingRange,

    currentPosition,

    recommendationStatus:
      "not_evaluated",

    calibratedProbability:
      null,

    reason,
  };
}